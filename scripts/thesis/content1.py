ABSTRACT_EN = (
    "Quantum circuit mapping is a core step in the compilation flow of the noisy "
    "intermediate-scale quantum (NISQ) era, aiming to determine qubit layouts and "
    "insert as few SWAP gates as possible so that mapped circuits can execute "
    "directly on real hardware. This thesis designs and implements QTrial, a "
    "complete circuit mapping optimization scheme targeting the Tianyan-287 "
    "superconducting processor (105 qubits, 15x7 grid). The scheme adopts a "
    "three-stage pipeline of reinforcement-learning-based layout, a self-developed "
    "SABRE router, and permutation-rewriting post-processing. The layout stage "
    "formulates the quadratic assignment problem as a policy network composed of "
    "graph attention networks and pointer networks, trained with a noise-weighted "
    "QAP cost as the sparse terminal reward, plus multi-start decoding and adaptive "
    "local search. The routing stage reproduces the SABRE algorithm with "
    "incremental frontier maintenance and Numba-fused kernels, completing "
    "hundred-qubit circuits within seconds. The post-processing stage eliminates "
    "SWAP gates via conjugation pushing, pair cancellation and trailing absorption, "
    "restricted to semantics-preserving transformations. In addition, LAUREL "
    "learned residual layers compress the training from 400 epochs to 89 epochs, "
    "and a QuEst-style graph Transformer fidelity predictor captures T1/T2 "
    "decoherence effects. On the stratified evaluation of 587 circuits from "
    "Benchpress, MQTBench and QUEKO, the scheme outperforms pytket and "
    "noise-blind baselines in overall estimated fidelity, and cross-topology "
    "experiments verify the effectiveness of the noise-aware mechanism."
)
